"""Python checker: every card becomes its own module.

1. `ruff check`  (if installed)  errors, unused names, common bug patterns
2. `pytest`      each card's `tests:` block runs in the card module's namespace,
                 so the asserts call the card's names directly; every concept
                 `code:` example is imported, so it has to run without errors.
"""
import importlib.util
import shutil
import subprocess
import sys


def run(items, workdir, opts):
    pkg = workdir / "cards"
    if pkg.exists():
        shutil.rmtree(pkg)
    pkg.mkdir(parents=True)
    (pkg / "__init__.py").write_text("", encoding="utf-8")
    tests = ["# AUTO-GENERATED by `asl check` - do not edit.", "import importlib", ""]
    for it in items:
        (pkg / f"{it.name}.py").write_text(f"# {it.label}\n{it.code.rstrip()}\n",
                                           encoding="utf-8")
        tests += [f"def test_{it.name}():",
                  f"    # {it.label}",
                  f"    ns = dict(vars(importlib.import_module('cards.{it.name}')))"]
        if it.kind == "solution" and it.tests.strip():
            tests.append(f"    exec(compile({it.tests.rstrip()!r}, '<{it.name} tests>', 'exec'), ns)")
        tests.append("")
    (workdir / "test_cards.py").write_text("\n".join(tests), encoding="utf-8")
    print(f"  modules: {pkg}")

    rc = 0
    # ruff ships with the tool (also inside `uv tool` / pipx environments, where it isn't on PATH)
    if importlib.util.find_spec("ruff"):
        ruff = [sys.executable, "-m", "ruff"]
    else:
        ruff = [shutil.which("ruff")] if shutil.which("ruff") else None
    if ruff and not opts.get("fast"):
        select = ",".join(opts.get("ruff_select", ["E", "F", "W", "B", "UP", "SIM"]))
        print(f"  => ruff check --select {select}")
        rc |= subprocess.run([*ruff, "check", "--quiet", "--no-cache", "--select", select,
                              "--ignore", "E501", str(pkg)]).returncode
    elif not ruff:
        print("  [!] ruff not found (pip install ruff); skipping lints.")
    print("  => pytest")
    rc |= subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider",
                          "test_cards.py"], cwd=workdir).returncode
    return rc
