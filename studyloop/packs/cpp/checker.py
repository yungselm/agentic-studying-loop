"""C++ checker: one translation unit, every card in its own namespace.

1. compile with warnings as errors and AddressSanitizer + UBSan  (`#line` makes every
   diagnostic name the card)
2. run each card's `tests:` (plain `assert`s) in its own process, so one failure
   doesn't hide the next and the sanitizer report names the card
3. clang-tidy with the Core Guidelines checks, if installed (skipped with --fast)

Card code may `#include` what it needs; includes are hoisted to the top of the file.
Concept `code:` examples sit at namespace scope: declarations, not loose statements.
"""
import os
import re
import shutil
import subprocess

INCLUDE = re.compile(r"^\s*#\s*include\s*[<\"][^>\"]+[>\"].*$", re.M)
HARNESS = ["<cassert>", "<cstdio>", "<cstring>"]


def compiler(opts):
    env = os.environ.get("ASL_CXX")
    if env:
        return shutil.which(env) and env
    return next((c for c in opts.get("compilers", ["g++", "clang++"]) if shutil.which(c)), None)


def _label(s):
    return re.sub(r'["\\\n]', "'", s)[:90]


def source(items):
    includes = list(dict.fromkeys(f"#include {h}" for h in HARNESS))
    body, tests = [], []
    for it in items:
        includes += [m.group(0).strip() for m in INCLUDE.finditer(it.code + "\n" + it.tests)]
        code = INCLUDE.sub("", it.code).rstrip()
        body += [f"namespace {it.name} {{", f'#line 1 "{_label(it.label)}"', code]
        if it.kind == "solution" and it.tests.strip():
            body += ["// NOLINTBEGIN", "void asl_test() {", f'#line 1 "{_label(it.label)} tests"',
                     INCLUDE.sub("", it.tests).rstrip(), "}", "// NOLINTEND"]
            tests.append(it)
        body += [f"}}  // namespace {it.name}", ""]
    main = ["// NOLINTBEGIN", "struct AslTest { const char* name; void (*run)(); };",
            "static const AslTest asl_tests[] = {",
            *[f'    {{"{it.name}", &{it.name}::asl_test}},' for it in tests],
            "    {nullptr, nullptr}};",
            "int main(int argc, char** argv) {",
            "    for (const AslTest* t = asl_tests; t->name; ++t)",
            "        if (argc < 2 || std::strcmp(argv[1], t->name) == 0) t->run();",
            "    return 0;", "}", "// NOLINTEND"]
    head = ["// AUTO-GENERATED by `asl check` - do not edit.", "#undef NDEBUG",
            *dict.fromkeys(includes), ""]
    return "\n".join(head + body + main) + "\n", tests


def run(items, workdir, opts):
    cxx = compiler(opts)
    std = os.environ.get("ASL_CXX_STD") or str(opts.get("std", "c++20"))
    src_text, tests = source(items)
    src = workdir / "cards.cpp"
    src.write_text(src_text, encoding="utf-8")
    print(f"  source: {src}")
    if not cxx:
        print("  [!] no C++ compiler found (g++ or clang++; set ASL_CXX); nothing was compiled.")
        return 2
    exe = workdir / "cards.out"
    san = ",".join(opts.get("sanitizers") or [])
    flags = [f"-std={std}", "-g", "-O1", *(opts.get("warnings") or [])]
    if san:
        flags += [f"-fsanitize={san}", "-fno-omit-frame-pointer", "-fno-sanitize-recover=all"]
    print(f"  => {cxx} {' '.join(flags)}")
    r = subprocess.run([cxx, *flags, str(src), "-o", str(exe)])
    if r.returncode:
        return r.returncode
    rc = 0
    env = dict(os.environ, ASAN_OPTIONS="detect_leaks=1", UBSAN_OPTIONS="print_stacktrace=1")
    print(f"  => run {len(tests)} test block(s)")
    for it in tests:
        t = subprocess.run([str(exe), it.name], capture_output=True, text=True, env=env)
        if t.returncode:
            rc = 1
            print(f"  [!] {it.label}\n" + "\n".join("      " + ln for ln in
                                                   (t.stderr or t.stdout).strip().splitlines()[:25]))
    if not opts.get("fast"):
        rc |= tidy(src, std, opts)
    return rc


def tidy(src, std, opts):
    exe = next((c for c in ["clang-tidy", *[f"clang-tidy-{v}" for v in range(19, 13, -1)]]
                if shutil.which(c)), None)
    if not exe:
        print("  [~] clang-tidy not found: Core Guidelines checks skipped "
              "(e.g. `sudo apt install clang-tidy`).")
        return 0
    checks = re.sub(r"\s+", "", str(opts.get("tidy_checks") or "")).strip(",")
    print(f"  => {exe} (Core Guidelines, bugprone, modernize, performance)")
    return subprocess.run([exe, "--quiet", f"--checks={checks}", "--warnings-as-errors=*",
                           str(src), "--", f"-std={std}"]).returncode
