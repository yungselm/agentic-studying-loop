"""Rust checker: one generated crate, every card in its own module.

1. `cargo clippy -- -D warnings`  compile errors, warnings, idiom lints
2. `cargo test`                   each card's `tests:` block (asserts)
"""
import os
import shutil
import subprocess
import textwrap


def _indent(s, n):
    return textwrap.indent(s.rstrip("\n"), " " * n)


def _module(it):
    if it.kind == "example":
        return (f"mod {it.name} {{\n    #![allow(dead_code, unused)]\n"
                f"    fn demo() {{\n{_indent(it.code, 8)}\n    }}\n}}")
    lines = [f"mod {it.name} {{", "    #![allow(dead_code)]", _indent(it.code, 4)]
    if it.tests.strip():
        # cfg(test): clippy (non-test build) doesn't lint the asserts
        lines += ["", "    #[cfg(test)]", "    mod tests {", "        use super::*;",
                  "        #[test]", "        fn card_test() {", _indent(it.tests, 12),
                  "        }", "    }"]
    lines.append("}")
    return "\n".join(lines)


def run(items, workdir, opts):
    edition = str(opts.get("edition", "2021"))
    src = workdir / "src"
    if src.exists():
        shutil.rmtree(src)
    src.mkdir(parents=True)
    (workdir / "Cargo.toml").write_text(
        f'[package]\nname = "card_check"\nversion = "0.0.0"\nedition = "{edition}"\n\n'
        '[lib]\npath = "src/lib.rs"\n', encoding="utf-8")
    parts = ["// AUTO-GENERATED by `asl check` - do not edit.\n"]
    for it in items:
        parts += [f"// {it.label}", _module(it), ""]
    (src / "lib.rs").write_text("\n".join(parts), encoding="utf-8")
    print(f"  crate: {workdir}")

    if not shutil.which("cargo"):
        print("  [!] no `cargo` on PATH (https://rustup.rs); nothing was compiled.")
        return 2
    env = dict(os.environ, RUSTFLAGS="-D warnings")
    rc = 0
    if not opts.get("fast"):
        print("  => cargo clippy -- -D warnings")
        rc |= subprocess.run(["cargo", "clippy", "--quiet", "--", "-D", "warnings"],
                             cwd=workdir, env=env).returncode
    print("  => cargo test")
    rc |= subprocess.run(["cargo", "test", "--quiet"], cwd=workdir, env=env).returncode
    return rc
